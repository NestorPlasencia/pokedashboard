import { mkdir, readFile, writeFile } from 'node:fs/promises';

const source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv';
// An optional local CSV permits regeneration without network access.
const csv = process.argv[2]
  ? await readFile(process.argv[2], 'utf8')
  : await fetch(source).then((response) => {
    if (!response.ok) throw new Error(`Unable to load Pokémon species: ${response.status}`);
    return response.text();
  });
const [header, ...lines] = csv.trim().split(/\r?\n/).map((line) => line.split(','));
const species = lines.map((values) => Object.fromEntries(header.map((key, index) => [key, values[index]])));
const entries = species.map((entry) => ({
  number: Number(entry.id), parent: Number(entry.evolves_from_species_id) || null,
}));
const seen = new Set();
// Use evolution parents: Phione and Manaphy share a breeding chain, but do not evolve.
const families = entries.filter((entry) => entry.parent === null).map((root) => {
  const ordered = [];
  const visit = (entry) => {
    if (seen.has(entry.number)) throw new Error('Cycle or duplicate species in evolution data.');
    seen.add(entry.number);
    ordered.push(entry.number);
    entries.filter((child) => child.parent === entry.number)
      .sort((a, b) => a.number - b.number).forEach(visit);
  };
  visit(root);
  return ordered;
}).filter((family) => family.length > 1).sort((a, b) => Math.min(...a) - Math.min(...b));
if (seen.size !== species.length) throw new Error('Disconnected species in evolution data.');

const output = `// Generated by scripts/update-pokemon-evolution.mjs from PokeAPI species data.
// Source: ${source}
// Covers national species #1–${Math.max(...species.map((entry) => Number(entry.id)))}.
// Families use parent-before-child traversal; sibling branches use national number.
// Species without evolutions are omitted and retain their national position.
export const POKEMON_EVOLUTION_FAMILIES: readonly (readonly number[])[] = [
${families.map((family) => `  [${family.join(', ')}],`).join('\n')}
];
`;
await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/data/pokemonEvolutionFamilies.ts', import.meta.url), output);
console.log(`Updated ${families.length} evolution families from ${species.length} species.`);
